/* ------------------------------------------------------------------ */
/* Pass 1: identifiers and CUDA builtins                              */
/* ------------------------------------------------------------------ */
static void rewrite_body(const char *src, sbuf *out)
{
    const char *p = src;

    while (*p) {
        /* Block comments: copy verbatim. */
        if (p[0] == '/' && p[1] == '*') {
            const char *e = strstr(p + 2, "*/");
            size_t n = e ? (size_t)(e + 2 - p) : strlen(p);
            sbuf_putn(out, p, n);
            p += n;
            continue;
        }
        /* Line comments */
        if (p[0] == '/' && p[1] == '/') {
            while (*p && *p != '\n')
                sbuf_putc(out, *p++);
            continue;
        }
        /* Strings and chars: copy verbatim. */
        if (*p == '"' || *p == '\'') {
            char quote = *p;
            sbuf_putc(out, *p++);
            while (*p && *p != quote) {
                if (*p == '\\' && p[1])
                    sbuf_putc(out, *p++);
                sbuf_putc(out, *p++);
            }
            if (*p)
                sbuf_putc(out, *p++);
            continue;
        }

        if (is_ident_start(*p)) {
            const char *start = p;
            while (is_ident_char(*p))
                p++;
            size_t n = (size_t)(p - start);

            char ident[64];
            if (n < sizeof(ident)) {
                memcpy(ident, start, n);
                ident[n] = '\0';
            } else {
                ident[0] = '\0';
            }

            if (strcmp(ident, "__global__") == 0) {
                sbuf_puts(out, "__kernel");
            } else if (strcmp(ident, "__device__") == 0 ||
                       strcmp(ident, "__host__") == 0 ||
                       strcmp(ident, "__noinline__") == 0 ||
                       strcmp(ident, "__device_builtin__") == 0) {
                /* drop */
            } else if (strcmp(ident, "__launch_bounds__") == 0 ||
                       strcmp(ident, "__align__") == 0 ||
                       strcmp(ident, "__builtin_align__") == 0) {
                p = skip_paren(p); /* drop token and its (...) */
            } else if (strcmp(ident, "__forceinline__") == 0 ||
                       strcmp(ident, "__inline__") == 0) {
                sbuf_puts(out, "inline");
            } else if (strcmp(ident, "__shared__") == 0) {
                sbuf_puts(out, "__local");
            } else if (strcmp(ident, "__constant__") == 0) {
                sbuf_puts(out, "__constant");
            } else if (strcmp(ident, "__restrict__") == 0) {
                sbuf_puts(out, "__restrict");
            } else {
                const char *fn = space_type(ident);
                if (fn) {
                    /* Possible threadIdx.x etc. Look ahead for .x/.y/.z */
                    const char *q = p;
                    while (*q == ' ' || *q == '\t')
                        q++;
                    if (q[0] == '.' && (q[1] == 'x' || q[1] == 'y' || q[1] == 'z') &&
                        !is_ident_char(q[2])) {
                        int dim = q[1] == 'x' ? 0 : (q[1] == 'y' ? 1 : 2);
                        char tmp[48];
                        snprintf(tmp, sizeof(tmp), "%s(%d)", fn, dim);
                        sbuf_puts(out, tmp);
                        p = q + 2;
                    } else {
                        sbuf_putn(out, start, n);
                    }
                } else {
                    sbuf_putn(out, start, n);
                }
            }
            continue;
        }

        sbuf_putc(out, *p++);
    }
}

/* ------------------------------------------------------------------ */
/* Pass 2: add __global to bare pointer parameters                    */
/* ------------------------------------------------------------------ */
static int has_address_space(const char *param, size_t len)
{
    static const char *kws[] = { "__global", "__local", "__constant", "__private" };
    for (size_t k = 0; k < sizeof(kws) / sizeof(kws[0]); k++) {
        size_t kl = strlen(kws[k]);
        for (size_t i = 0; i + kl <= len; i++) {
            if (strncmp(param + i, kws[k], kl) == 0) {
                int left_ok = (i == 0) || !is_ident_char(param[i - 1]);
                int right_ok = (i + kl == len) || !is_ident_char(param[i + kl]);
                if (left_ok && right_ok)
                    return 1;
            }
        }
    }
    return 0;
}

static int param_has_pointer(const char *param, size_t len)
{
    for (size_t i = 0; i < len; i++)
        if (param[i] == '*')
            return 1;
    return 0;
}

/* Find the matching close paren for the '(' at src[open]. Returns index or 0. */
static size_t match_paren(const char *s, size_t open)
{
    int depth = 0;
    for (size_t i = open; s[i]; i++) {
        if (s[i] == '(')
            depth++;
        else if (s[i] == ')') {
            depth--;
            if (depth == 0)
                return i;
        }
    }
    return 0;
}

static void insert_global_qualifiers(const char *src, sbuf *out)
{
    const char *p = src;

    while (*p) {
        if (is_ident_start(*p)) {
            const char *start = p;
            while (is_ident_char(*p))
                p++;
            size_t n = (size_t)(p - start);

            if (n == 8 && strncmp(start, "__kernel", 8) == 0) {
                sbuf_puts(out, "__kernel");
                /* find '(' */
                const char *q = p;
                while (*q && *q != '(')
                    q++;
                if (!*q) {
                    continue;
                }
                size_t open = (size_t)(q - src);
                size_t close = match_paren(src, open);
                if (close == 0) {
                    sbuf_puts(out, q);
                    p = q + strlen(q);
                    continue;
                }
                /* copy text between __kernel and '(' */
                sbuf_putn(out, p, (size_t)(q - p));
                sbuf_putc(out, '(');
                /* process parameters src[open+1 .. close-1] */
                size_t ps = open + 1, pe = close;
                size_t i = ps;
                size_t seg_start = ps;
                int first = 1;
                while (i <= pe) {
                    int at_end = (i == pe);
                    /* split on top-level commas */
                    if (at_end || src[i] == ',') {
                        const char *seg = src + seg_start;
                        size_t seg_len = i - seg_start;
                        /* trim leading whitespace */
                        size_t lead = 0;
                        while (lead < seg_len && isspace((unsigned char)seg[lead]))
                            lead++;
                        size_t body_len = seg_len - lead;
                        const char *body = seg + lead;

                        if (!first)
                            sbuf_putc(out, ',');
                        sbuf_putc(out, ' ');
                        if (body_len > 0 && param_has_pointer(body, body_len) &&
                            !has_address_space(body, body_len)) {
                            sbuf_puts(out, "__global ");
                        }
                        sbuf_putn(out, body, body_len);
                        first = 0;
                        seg_start = i + 1;
                    }
                    i++;
                }
                sbuf_putc(out, ')');
                p = src + close + 1;
                continue;
            }
            sbuf_putn(out, start, n);
            continue;
        }
        sbuf_putc(out, *p++);
    }
}

/* ------------------------------------------------------------------ */
/* Public entry point                                                 */
/* ------------------------------------------------------------------ */
char *muda_translate_cuda_to_opencl(const char *source)
{
    if (!source)
        return NULL;

    sbuf pass1;
    sbuf_init(&pass1);
    if (!pass1.data)
        return NULL;
    rewrite_body(source, &pass1);

    sbuf final;
    sbuf_init(&final);
    if (!final.data) {
        free(pass1.data);
        return NULL;
    }
    sbuf_puts(&final, kPreamble);
    insert_global_qualifiers(pass1.data, &final);
    sbuf_putc(&final, '\n');

    free(pass1.data);
    return final.data;
}
