/*
 * muda_translate.c - translate CUDA-style kernel source into OpenCL C.
 *
 * This is intentionally a small, readable token rewriter rather than a real
 * compiler.  It handles the parts of CUDA C that differ syntactically from
 * OpenCL C:
 *
 *   __global__        -> __kernel
 *   __device__/__host__ -> (removed)
 *   __shared__        -> __local
 *   threadIdx.x/y/z   -> get_local_id(0/1/2)
 *   blockIdx.x/y/z    -> get_group_id(0/1/2)
 *   blockDim.x/y/z    -> get_local_size(0/1/2)
 *   gridDim.x/y/z     -> get_num_groups(0/1/2)
 *
 * It also inserts the required __global address-space qualifier on bare
 * pointer parameters of kernel functions, so users can write
 *
 *     __global__ void vadd(const float *a, const float *b, float *c)
 *
 * exactly as they would in CUDA.
 */

#include "muda_internal.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

/* ------------------------------------------------------------------ */
/* Tiny growable string buffer                                        */
/* ------------------------------------------------------------------ */
typedef struct {
    char *data;
    size_t len;
    size_t cap;
} sbuf;

static void sbuf_init(sbuf *b)
{
    b->cap = 256;
    b->len = 0;
    b->data = (char *)malloc(b->cap);
    if (b->data)
        b->data[0] = '\0';
}

static void sbuf_reserve(sbuf *b, size_t extra)
{
    if (b->len + extra + 1 <= b->cap)
        return;
    while (b->cap < b->len + extra + 1)
        b->cap *= 2;
    b->data = (char *)realloc(b->data, b->cap);
}

static void sbuf_putc(sbuf *b, char c)
{
    sbuf_reserve(b, 1);
    b->data[b->len++] = c;
    b->data[b->len] = '\0';
}

static void sbuf_puts(sbuf *b, const char *s)
{
    size_t n = strlen(s);
    sbuf_reserve(b, n);
    memcpy(b->data + b->len, s, n);
    b->len += n;
    b->data[b->len] = '\0';
}

static void sbuf_putn(sbuf *b, const char *s, size_t n)
{
    sbuf_reserve(b, n);
    memcpy(b->data + b->len, s, n);
    b->len += n;
    b->data[b->len] = '\0';
}

/* ------------------------------------------------------------------ */
/* Token helpers                                                      */
/* ------------------------------------------------------------------ */
static int is_ident_start(char c)
{
    return isalpha((unsigned char)c) || c == '_';
}

static int is_ident_char(char c)
{
    return isalnum((unsigned char)c) || c == '_';
}

static const char *space_type(const char *name)
{
    if (strcmp(name, "threadIdx") == 0) return "get_local_id";
    if (strcmp(name, "blockIdx")  == 0) return "get_group_id";
    if (strcmp(name, "blockDim")  == 0) return "get_local_size";
    if (strcmp(name, "gridDim")   == 0) return "get_num_groups";
    return NULL;
}

/* Skip whitespace then a balanced parenthesised group (used to drop
 * qualifiers such as __launch_bounds__(...) and __align__(...)). */
static const char *skip_paren(const char *p)
{
    while (*p == ' ' || *p == '\t' || *p == '\n' || *p == '\r')
        p++;
    if (*p != '(')
        return p;
    int depth = 0;
    while (*p) {
        if (*p == '(') {
            depth++;
        } else if (*p == ')') {
            depth--;
            p++;
            if (depth == 0)
                break;
            continue;
        }
        p++;
    }
    return p;
}

